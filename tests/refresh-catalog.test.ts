import { test, expect } from "bun:test";
import { mkdtemp, mkdir, writeFile, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { createHash } from "node:crypto";
import { refresh, OWNERS, INITIAL_COMMIT, type Source } from "../scripts/refresh-catalog";

for (const scenario of ["unclassified addition", "assigned removal"]) {
  test(`${scenario} names the capability and preserves every generated byte`, async () => {
    const root = await mkdtemp(join(tmpdir(), "catalog-regression-"));
    try {
      const upstream = new Map<string, Uint8Array>();
      const names = new Set(["router", "careful", "freeze", "guard", "unfreeze", ...Object.values(OWNERS).flat(), "plan-eng-review", "claude-code", "captain", "runaway-stopper", "gstack-upgrade"]);
      for (const name of names) {
        const path = name === "router" ? "SKILL.md" : `${name}/SKILL.md`;
        const bytes = new TextEncoder().encode(`---\nname: ${name === "router" ? "gstack" : name}\ndescription: Synthetic capability for failure-boundary testing\n---\nCanonical fixture method.\n`);
        upstream.set(`${path}.tmpl`, bytes);
        if (name !== "claude-code") upstream.set(path, bytes);
      }
      upstream.set("VERSION", new TextEncoder().encode("1.99.0.0\n"));
      await mkdir(join(root, "templates"), { recursive: true });
      await writeFile(join(root, "templates/gstack-runtime.md"), "Pin {{GSTACK_COMMIT}}, version {{GSTACK_VERSION}}\n");
      for (const [owner, skills] of Object.entries(OWNERS)) {
        const file = join(root, `agents/${owner}/AGENTS.md`);
        await mkdir(dirname(file), { recursive: true });
        const bindings = ["gstack-runtime", ...["router", "careful", "freeze", "guard", "unfreeze", ...skills].map(name => `gstack-${name}`)];
        await writeFile(file, `---\nname: ${owner}\nskills:\n${bindings.map(name => `  - "${name}"`).join("\n")}\n---\n`);
      }
      const source: Source = { paths: [...upstream.keys()], read: async path => {
        const bytes = upstream.get(path);
        if (!bytes) throw new Error(`Missing fixture ${path}`);
        return bytes;
      } };
      const generated = await refresh(root, source, INITIAL_COMMIT, {});
      const before = new Map(await Promise.all(generated.map(async path => [path, createHash("sha256").update(await readFile(join(root, path))).digest("hex")] as const)));
      if (scenario === "unclassified addition") source.paths.push("new-unreviewed/SKILL.md.tmpl");
      else source.paths = source.paths.filter(path => path !== "review/SKILL.md.tmpl");
      await expect(refresh(root, source, INITIAL_COMMIT, {})).rejects.toThrow(scenario === "unclassified addition" ? "Unclassified: new-unreviewed" : "removed assigned: review");
      for (const [path, hash] of before) expect(createHash("sha256").update(await readFile(join(root, path))).digest("hex")).toBe(hash);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
}
